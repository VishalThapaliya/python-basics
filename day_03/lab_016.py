# List, Set, Tuple and Dictionary in Python

# A list is an ordered collection of items which can be of any type - Array
fruits = ["Apple", "Banana", "Cherry", "Apple"]
print(fruits)

# Add an item to a list
fruits.append("Orange")
print(fruits)

# Remove an item from a list
# fruits.remove("Apple")
# print(fruits)

# slicing
print(fruits[0:3]) # from 0th till below 3rd index (i.e. 3-1 = 2nd index)

# reverse a list
fruits.reverse()
print(fruits)